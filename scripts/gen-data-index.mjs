// Generate src/data/cityLoaders.js from data/cities.json.
// Each city's detail JSON becomes a lazily-loaded Parcel chunk,
// so the initial bundle stays small.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const cities = JSON.parse(readFileSync(join(root, "data", "cities.json"), "utf8"));

const lines = cities
  .map(
    (c) =>
      `  ${JSON.stringify(c.pinyin)}: () => import(${JSON.stringify(`../../data/cities/${c.pinyin}.json`)})`,
  )
  .join(",\n");

const out = `// AUTO-GENERATED by scripts/gen-data-index.mjs - do not edit manually.
export const cityLoaders = {
${lines},
};

export const cityPinyinList = ${JSON.stringify(cities.map((c) => c.pinyin))};
`;

writeFileSync(join(root, "src", "data", "cityLoaders.js"), out, "utf8");
console.log(`[gen-data-index] ${cities.length} city loaders -> src/data/cityLoaders.js`);
